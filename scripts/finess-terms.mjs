#!/usr/bin/env node
/**
 * FINESS+ — the official labels the directory shows, from the ANS terminology implementation guide (« Guide d'implémentation des terminologies de santé »,
 * https://ansforge.github.io/IG-terminologie-de-sante, the source the FINESS publisher documents in github.com/ansforge/finess docs/referentiels/terminologies-smt.md).
 * Writes api/_services/verification/finess-terms.js (a module: bundled with the functions like any code): for each terminology its official name, version and date, and the code → label pairs the directory uses
 * (the categories of establishment in scope: SCOPE of finess.js; every public, activity and mode of the regulated social / medico-social activities).
 *   node scripts/finess-terms.mjs               download the CodeSystems (network: ansforge.github.io)
 *   node scripts/finess-terms.mjs --from <dir>  read CodeSystem-<id>.json files already downloaded there (offline)
 * Run again when the terminologies change (the guide's version is in the file): the veille never fetches them itself.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCOPE } from '../api/_services/verification/finess-scope.js';

const IG = 'https://ansforge.github.io/IG-terminologie-de-sante/ig/main/';
const SYSTEMS = { categorie: 'tre-r397-categorie-entite-geographique-exercice', activite: 'tre-r401-activite-sociale-regulee', public: 'tre-r403-public-activite-smsse-regulee',
  mode: 'tre-r404-mode-fonctionnement-activite-smsse-regulee', etat: 'tre-r386-macro-etat-objet-administratif' };
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'api', '_services', 'verification', 'finess-terms.js');

const from = process.argv.includes('--from') ? process.argv[process.argv.indexOf('--from') + 1] : null;
async function load(id) {
  if (from) return JSON.parse(fs.readFileSync(path.join(from, `${id}.json`), 'utf8'));
  const r = await fetch(`${IG}CodeSystem-${id}.json`, { headers: { Accept: 'application/json' } });
  if (!r.ok) throw new Error(`${id}: HTTP ${r.status}`);
  return r.json();
}
const flat = (concepts, out = {}) => { for (const c of concepts || []) { if (c.code) out[c.code] = c.display || null; flat(c.concept, out); } return out; };

const terms = { source: IG, generatedBy: 'scripts/finess-terms.mjs', systems: {} };
for (const [key, id] of Object.entries(SYSTEMS)) {
  const cs = await load(id); const all = flat(cs.concept);
  const codes = key === 'categorie' ? Object.fromEntries(Object.keys(SCOPE).sort().map((c) => [c, all[c] ?? null])) : all;
  const missing = Object.entries(codes).filter(([, v]) => !v).map(([c]) => c);
  if (missing.length) throw new Error(`${id}: codes sans libellé officiel ${missing.join(', ')}`);
  terms.systems[key] = { id, url: cs.url || null, name: cs.name || null, version: cs.version || null, date: cs.date || null, codes };
}
fs.writeFileSync(OUT, `// Generated by scripts/finess-terms.mjs from the ANS terminologies (do not edit by hand).\nexport default ${JSON.stringify(terms, null, 1)};\n`);
console.log(`finess-terms.js: ${Object.entries(terms.systems).map(([k, s]) => `${k} ${Object.keys(s.codes).length} (v${s.version})`).join(', ')}`);
