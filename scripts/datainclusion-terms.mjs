#!/usr/bin/env node
/**
 * data·inclusion (D05) — the official labels of the data·inclusion schema the directory shows (thématiques, publics, frais, modes d'accueil, types de services),
 * from the schema's own repository (github.com/gip-inclusion/data-inclusion-schema, Licence Ouverte 2.0), at a PINNED commit: the labels change only when this
 * script is run again on purpose. Writes api/_services/verification/datainclusion-terms.js (a module: bundled with the functions like any code).
 *   node scripts/datainclusion-terms.mjs               download the referentials (network: raw.githubusercontent.com)
 *   node scripts/datainclusion-terms.mjs --from <dir>  read <name>.json files already downloaded there (offline)
 * The veille never fetches them itself; a value of the export missing from these referentials is counted and not shown.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'gip-inclusion/data-inclusion-schema';
const COMMIT = '5b6e3806b4b528310fe218fd8693f4e5b3ab5fe9';   // 2026-09-22, the last change of schemas/v1/extra before the 2026-10-20 export
const SCHEMA = 'v1';
const LISTS = { thematiques: 'thematiques', publics: 'publics', frais: 'frais', modesAccueil: 'modes-accueil', types: 'types-de-services' };
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'api', '_services', 'verification', 'datainclusion-terms.js');

const from = process.argv.includes('--from') ? process.argv[process.argv.indexOf('--from') + 1] : null;
async function load(name) {
  if (from) return JSON.parse(fs.readFileSync(path.join(from, `${name}.json`), 'utf8'));
  const r = await fetch(`https://raw.githubusercontent.com/${REPO}/${COMMIT}/schemas/${SCHEMA}/extra/${name}.json`, { headers: { Accept: 'application/json' } });
  if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
  return r.json();
}

const terms = { source: `https://github.com/${REPO}/tree/${COMMIT}/schemas/${SCHEMA}/extra`, schema: SCHEMA, commit: COMMIT, licence: 'Licence Ouverte 2.0', generatedBy: 'scripts/datainclusion-terms.mjs', lists: {} };
for (const [key, name] of Object.entries(LISTS)) {
  const items = await load(name);
  if (!Array.isArray(items) || !items.length) throw new Error(`${name}: liste vide ou illisible`);
  const codes = Object.fromEntries(items.map((x) => [String(x.value), String(x.label || '').trim()]));
  const missing = Object.entries(codes).filter(([, v]) => !v).map(([c]) => c);
  if (missing.length) throw new Error(`${name}: valeurs sans libellé ${missing.join(', ')}`);
  terms.lists[key] = codes;
}
fs.writeFileSync(OUT, `// Generated by scripts/datainclusion-terms.mjs from the data·inclusion schema (do not edit by hand).\nexport default ${JSON.stringify(terms, null, 1)};\n`);
console.log(`datainclusion-terms.js: ${Object.entries(terms.lists).map(([k, s]) => `${k} ${Object.keys(s).length}`).join(', ')} (schéma ${SCHEMA}, ${COMMIT.slice(0, 7)})`);
