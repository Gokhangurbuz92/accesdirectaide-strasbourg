#!/usr/bin/env node
/**
 * UI modernisation (24/11/2026) — generates src/styles/theme-palette.css: every Tailwind colour used by the screens becomes a CSS variable, in three
 * roles (text / border / background), so ONE stylesheet gives the whole site a consistent dark theme and a stronger high-contrast mode without
 * touching the ~5,000 colour classes of the components.
 *
 *  - Light: every variable equals the Tailwind default value — the light rendering (and every contrast test run in light) is unchanged.
 *  - Dark (html.dark — the theme toggle, and « system » when the device is dark — and html.dark-mode, the accessibility panel's dark choice):
 *      background 50–400 (tinted panels) → dark tints; 500–950 (solid buttons with white text) keep their value;
 *      text 500–950 (dark text written for a light page) → light tints; 50–400 keep their value (they are already light, used on solid fills);
 *      border 50–400 → dark lines; 500+ → light lines; ring / outline follow the text role (a focus ring stays bright).
 *  - High contrast (html.high-contrast, light): grey text darkens to near black.
 * Usage: node scripts/gen-theme-palette.mjs [--check]   (--check exits 1 when the committed file is stale)
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const twColors = require('tailwindcss/colors');
const { PALETTE_FAMILIES, NEUTRALS, SHADES, DARK } = require('../src/design/palette.cjs');

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/styles/theme-palette.css');

const hex2rgb = (h) => { const x = h.replace('#', ''); const n = parseInt(x.length === 3 ? x.split('').map((c) => c + c).join('') : x, 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255]; };
const triplet = (h) => hex2rgb(h).join(' ');
/** a over b with weight w (0..1) */
const mix = (a, b, w) => { const A = hex2rgb(a); const B = hex2rgb(b); return '#' + A.map((v, i) => Math.round(v * w + B[i] * (1 - w)).toString(16).padStart(2, '0')).join(''); };

const light = [];
const dark = [];
for (const f of PALETTE_FAMILIES) {
  for (const s of SHADES) {
    const v = twColors[f][s];
    light.push(`  --c-${f}-${s}: ${triplet(v)};`);   // one value per colour in light; the role variables (--ct / --cb / --cg) are set only where a mode changes them
    const neutral = NEUTRALS.includes(f);
    // text role
    const textDark = Number(s) >= 500 ? (neutral ? DARK.neutralText[s] : twColors[f][DARK.textShade[s]]) : v;
    // background role
    const bgDark = Number(s) <= 400 ? (neutral ? DARK.neutralBg[s] : mix(twColors[f][500], DARK.surface, DARK.tintWeight[s])) : v;
    // border role
    const borderDark = Number(s) <= 400 ? (neutral ? DARK.neutralBorder[s] : mix(twColors[f][400], DARK.surface, DARK.borderWeight[s])) : (neutral ? DARK.neutralText[s] : twColors[f][DARK.textShade[s]]);
    if (textDark !== v) dark.push(`  --ct-${f}-${s}: ${triplet(textDark)};`);
    if (borderDark !== v) dark.push(`  --cb-${f}-${s}: ${triplet(borderDark)};`);
    if (bgDark !== v) dark.push(`  --cg-${f}-${s}: ${triplet(bgDark)};`);
  }
}
light.push('  --cg-white: 255 255 255;');
dark.push(`  --cg-white: ${triplet(DARK.surface)};`);

// high contrast (light page): grey text from 500 up becomes near black, coloured text the darkest shade of its family
const hc = [];
// 400 and lighter stay: they are light text on dark fills (badges)
for (const f of PALETTE_FAMILIES) for (const s of ['500', '600', '700', '800']) hc.push(`  --ct-${f}-${s}: ${triplet(NEUTRALS.includes(f) ? '#111111' : twColors[f][900])};`);

const css = `/* GENERATED by scripts/gen-theme-palette.mjs — do not edit by hand (node scripts/gen-theme-palette.mjs). See the header of that script. */
:root {
${light.join('\n')}
}

:root:is(.dark, .dark-mode) {
  color-scheme: dark;
${dark.join('\n')}
}

:root.high-contrast:not(.dark):not(.dark-mode) {
${hc.join('\n')}
}
`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== css) { console.error('theme-palette.css is stale: run node scripts/gen-theme-palette.mjs'); process.exit(1); }
  console.log('theme-palette.css up to date');
} else {
  fs.writeFileSync(OUT, css);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${light.length} light, ${dark.length} dark, ${hc.length} high-contrast variables)`);
}
